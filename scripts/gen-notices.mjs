// Generates THIRD_PARTY_NOTICES.md: every third-party component that ships inside the built app,
// with its license text. Runtime npm dependencies are read from node_modules automatically.
// Usage: node scripts/gen-notices.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

